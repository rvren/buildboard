/** Codegen uses `LinkIcon` alias for the reserved `Link` name to avoid clashes. */
export function iconImportName(name: string): string {
  return name === "Link" ? "Link as LinkIcon" : name;
}
export function iconJsxName(name: string): string {
  return name === "Link" ? "LinkIcon" : name;
}
